"""New LucaVirus v1.0 nucleotide embedding inference (2560-d). No feature import.

Calls the official LucaVirusTasks/src/llm/lucavirus/get_embedding.py with the
same v1.0, 20240815023346 / 3800000, seq_type=gene, vector, complete,
4096-per-chunk parameters as the original server 08/13 scripts.
Consumes *only* freshly generated vector_<TaxID>.pt files, verifies every TaxID
against this run's input FASTA and writes features.npy+ids.tsv in FASTA order.
Requires a local cloned LucaVirusTasks repo, authentic foundation checkpoint,
and torch-compatible environment; fail rather than substitute vectors.
"""
from __future__ import annotations
import argparse
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile
import numpy as np
from .common import CLASSES,LENGTHS,fasta_records,load_ids,write_ids,write_fasta_record,sha256sum

DIM=2560

def load_pt_vector(path):
    import torch
    # Only load PT files freshly generated by the researcher-owned official model.
    try:
        value=torch.load(path,map_location='cpu',weights_only=True)
    except Exception as e:
        raise ValueError(f'Cannot safely load model vector {path}: {e}') from e
    if torch.is_tensor(value):value=value.detach().cpu().numpy()
    value=np.asarray(value).reshape(-1)
    if value.size!=DIM or not np.isfinite(value).all():
        raise ValueError(f'{path}: expected finite {DIM}-D embedding, got {value.shape}')
    return value.astype(np.float32)

def infer_class(sequence_root,feature_root,length,cls,repo,gpu_id=-1,chunk_size=1000,python_executable=sys.executable):
    """Run fresh LucaVirus inference, reusing verified PT outputs after interruption."""
    repo=Path(repo).resolve()
    script=repo/'src/llm/lucavirus/get_embedding.py'
    if not script.is_file():raise FileNotFoundError(f'Official LucaVirus inference script not found: {script}')
    source=Path(sequence_root)/length/f'{cls}_{length}.fasta'
    idsfile=Path(sequence_root)/length/f'{cls}_ids.tsv'
    ids=load_ids(idsfile)
    if any(label!=cls for _,label in ids):raise ValueError('Bad class label')
    output=Path(feature_root)/length/'LucaVirus'/cls
    fingerprint={'input_sha256':sha256sum(source),'ids_sha256':sha256sum(idsfile),
                 'script_sha256':sha256sum(script),'llm_version':'v1.0',
                 'llm_time_str':'20240815023346','llm_step':3800000,
                 'chunk_size':chunk_size,'embedding_fixed_len_a_time':4096}
    expected=[tid for tid,_ in ids]
    final=output/'features.npy'
    if final.is_file() and (output/'ids.tsv').is_file() and (output/'inference_manifest.json').is_file():
        metadata=json.loads((output/'inference_manifest.json').read_text())
        if (metadata.get('input_fingerprint')==fingerprint and load_ids(output/'ids.tsv')==ids and
            np.load(final,mmap_mode='r').shape==(len(expected),DIM)):
            print(f'[SKIP] Verified LucaVirus {length}/{cls}',flush=True)
            return
        raise RuntimeError(f'Existing LucaVirus embedding does not match input: {output}')
    output.mkdir(parents=True,exist_ok=True)
    statefile=output/'progress.json'
    if statefile.is_file():
        if json.loads(statefile.read_text()).get('input_fingerprint')!=fingerprint:
            raise RuntimeError(f'LucaVirus input or model source changed since partial run: {output}')
    elif any(output.iterdir()):
        raise RuntimeError(f'Unknown unfinished LucaVirus output at {output}; inspect manually')
    else:
        statefile.write_text(json.dumps({'input_fingerprint':fingerprint},indent=2)+'\n')
    raw=output/'raw_vectors';raw.mkdir(exist_ok=True)
    chunks=output/'input_chunks';chunks.mkdir(exist_ok=True)
    try:
        chunk_manifest=[];idx=0;handle=None;count_in_chunk=0;chunk_idx=0;ids_this_chunk=[]
        def close_chunk():
            nonlocal handle,count_in_chunk,ids_this_chunk
            if handle is not None:
                handle.close();handle=None
                chunk_manifest.append((chunk_path,list(ids_this_chunk)))
                ids_this_chunk=[];count_in_chunk=0
        for tid,header,seq in fasta_records(source):
            if idx>=len(ids) or tid!=expected[idx]:
                raise ValueError(f'Input FASTA ID order mismatch: {length}/{cls} idx={idx}')
            if handle is None:
                chunk_idx+=1
                chunk_path=chunks/f'part_{chunk_idx:05d}.fasta'
                handle=chunk_path.open('w',encoding='utf-8')
            write_fasta_record(handle,tid,seq)
            ids_this_chunk.append(tid)
            count_in_chunk+=1;idx+=1
            if count_in_chunk>=chunk_size:close_chunk()
        if handle is not None:close_chunk()
        if idx!=len(expected):raise ValueError(f'Input count mismatch: {idx} != {len(expected)}')
        for i,(input_fasta,chunk_ids) in enumerate(chunk_manifest,1):
            # Resume only from OUR own progress directory, verify each PT shape/value.
            already=True
            for tid in chunk_ids:
                vec=raw/f'vector_{tid}.pt'
                if not vec.is_file():already=False;break
                try:load_pt_vector(vec)
                except (ValueError,RuntimeError,EOFError,OSError):already=False;break
            if already:
                print(f'[LucaVirus] Resume: verified batch {i}/{len(chunk_manifest)}, skipping',flush=True)
                continue
            cmd=[python_executable,str(script),'--llm_dir',str(repo),'--llm_type','lucavirus',
                 '--llm_version','v1.0','--llm_time_str','20240815023346',
                 '--llm_step','3800000','--seq_type','gene',
                 '--input_file',str(input_fasta.resolve()),'--save_path',str(raw.resolve()),
                 '--embedding_type','vector','--embedding_complete',
                 '--embedding_fixed_len_a_time','4096','--gpu_id',str(gpu_id)]
            print(f'[LucaVirus] {length}/{cls} NEW inference batch {i}/{len(chunk_manifest)}',flush=True)
            subprocess.run(cmd,cwd=repo,check=True)
        actual={p.name[len('vector_'):-len('.pt')]:p for p in raw.glob('vector_*.pt')}
        if set(actual)!=set(expected):
            missing=set(expected)-set(actual);extra=set(actual)-set(expected)
            raise ValueError(f'PT/FASTA TaxID mismatch; missing={len(missing)} {list(missing)[:5]}, extra={len(extra)} {list(extra)[:5]}')
        matrix=np.lib.format.open_memmap(output/'features.npy.part',mode='w+',dtype=np.float32,shape=(len(expected),DIM))
        for i,tid in enumerate(expected):
            matrix[i]=load_pt_vector(actual[tid])
            if (i+1)%1000==0 or i+1==len(expected):
                print(f'[LucaVirus] convert {length}/{cls} {i+1}/{len(expected)}',flush=True)
        matrix.flush();del matrix
        try:
            commit=subprocess.check_output(['git','-C',str(repo),'rev-parse','HEAD'],text=True,stderr=subprocess.DEVNULL).strip()
        except Exception:commit=None
        record={'lucavirus_tasks_commit':commit,'foundation_model':'LucaVirus','llm_version':'v1.0',
                'llm_time_str':'20240815023346','llm_step':3800000,'seq_type':'gene',
                'embedding_type':'vector','embedding_complete':True,'embedding_fixed_len_a_time':4096,
                'gpu_id':gpu_id,'repo':str(repo),'script_sha256':sha256sum(script),
                'count':len(expected),'dimension':DIM,'input_fingerprint':fingerprint}
        (output/'inference_manifest.json.tmp').write_text(json.dumps(record,indent=2)+'\n')
        os.replace(output/'features.npy.part',final)
        write_ids(output/'ids.tsv',ids)
        os.replace(output/'inference_manifest.json.tmp',output/'inference_manifest.json')
        statefile.unlink(missing_ok=True)
        (output/'FAILED.txt').unlink(missing_ok=True)
        print(f'[DONE] LucaVirus {length}/{cls} ({len(expected)},{DIM})',flush=True)
    except BaseException:
        (output/'FAILED.txt').write_text('Interrupted or failed. Rerun with unchanged input/model source to resume.\n')
        raise

def main(argv=None):
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--sequences',required=True);p.add_argument('--features-dir',required=True)
    p.add_argument('--length',choices=LENGTHS,required=True);p.add_argument('--class-name',choices=CLASSES,required=True)
    p.add_argument('--lucavirus-tasks',required=True)
    p.add_argument('--gpu-id',type=int,default=-1);p.add_argument('--chunk-size',type=int,default=1000)
    p.add_argument('--python',default=sys.executable)
    a=p.parse_args(argv)
    if a.chunk_size<1:p.error('chunk-size must be >=1')
    infer_class(a.sequences,a.features_dir,a.length,a.class_name,a.lucavirus_tasks,a.gpu_id,a.chunk_size,a.python)
if __name__=='__main__':main()
